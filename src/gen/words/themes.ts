/**
 * Pick words from a theme whose letters add up to `area` exactly (between
 * `min` and `max` words, no word twice, none longer than `longest`), or null.
 */
export function pickWords(
  theme: Theme,
  area: number,
  min: number,
  max: number,
  longest: number,
  random: () => number,
): string[] | null {
  const pool = [...new Set(theme.words)].filter((w) => w.length >= 3 && w.length <= longest);
  for (let tries = 0; tries < 400; tries++) {
    const shuffled = pool.map((w) => [random(), w] as const).sort((a, b) => a[0] - b[0]);
    const chosen: string[] = [];
    let sum = 0;
    for (const [, w] of shuffled) {
      if (chosen.length >= max) break;
      if (sum + w.length > area) continue;
      // Leave room only for a gap some word could fill (at least 3 letters), or none.
      const left = area - sum - w.length;
      if (left > 0 && left < 3) continue;
      chosen.push(w);
      sum += w.length;
      if (sum === area) break;
    }
    if (sum === area && chosen.length >= min) return chosen;
  }
  return null;
}
